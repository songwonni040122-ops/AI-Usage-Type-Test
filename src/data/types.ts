/** 코드 → 유형 빠른 조회 */
export const typeByCode: Record<string, AIType> = types.reduce(
  (acc, t) => {
    acc[t.code] = t
    return acc
  },
  {} as Record<string, AIType>,
)

/** 유효한 유형 코드인지 확인 */
export function isValidCode(code: string | null | undefined): code is string {
  return !!code && Object.prototype.hasOwnProperty.call(typeByCode, code)
}
